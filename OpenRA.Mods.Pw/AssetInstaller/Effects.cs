using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using OpenRA.Primitives;

namespace OpenRA.Mods.Pw.AssetInstaller
{
	// Weapon effects (JW2_12 .wpn, docs/formats/effect.md): each weapon's art becomes image weapon-<name> in
	// effects/<image>.png with a "flight" sequence (the projectile: 8 facings x flight/8 frames when directional,
	// otherwise a tumbling loop) and an "impact" sequence; its sounds become sounds/<image>-<n>.wav. The weapons in
	// weapons/*.yaml reference them. The spells and abilities (JW2_11) become spell-<name>, all frames as "effect".
	public static class Effects
	{
		const int Record = 0xadc;
		const string Header = "# Generated by install-assets (OpenRA.Mods.Pw/AssetInstaller/Effects.cs); do not edit.\n\n";

		// Impacts are drawn smaller than the original art: half size, the Giant's bomb a quarter.
		static string ImpactScale(string image) => image == "weapon-throw-bomb" ? "0.25" : "0.5";

		public static string Image(string name) => "weapon-" + Regex.Replace(name.ToLowerInvariant(), "[^a-z0-9]+", "-").Trim('-');

		public static void Export(InstallContext c)
		{
			var sequences = new StringBuilder(Header);
			foreach (var data in Records(c.Game.Archive("Jw2_12.trc")))
			{
				var (name, palette, frames, sounds) = ReadRecord(data);
				var image = Image(name);
				var flight = BitConverter.ToInt32(data, 0x208);
				var impact = BitConverter.ToInt32(data, 0x20c);
				var directional = BitConverter.ToInt32(data, 0x1fc) == 1;
				WriteSounds(c, image, sounds);
				if (frames.Count == 0)
					continue;

				c.WriteFile($"effects/{image}.png", Units.Sheet(frames, palette));
				sequences.Append($"{image}:\n\tDefaults:\n\t\tFilename: effects/{image}.png\n");
				if (flight > 0)
				{
					if (directional && flight % 8 == 0)
					{
						// The art's eight blocks start one step clockwise of north: block k points at facing k + 1.
						var n = flight / 8;
						var order = Enumerable.Range(0, 8).SelectMany(d => Enumerable.Range((d + 7) % 8 * n, n));
						sequences.Append($"\tflight:\n\t\tFacings: -8\n\t\tLength: {n}\n\t\tFrames: {string.Join(", ", order)}\n");
					}
					else
						sequences.Append($"\tflight:\n\t\tLength: {flight}\n");
				}

				var scale = ImpactScale(image);
				if (impact > 0)
					sequences.Append($"\timpact:\n\t\tStart: {flight}\n\t\tLength: {impact}\n\t\tScale: {scale}\n");

				// Art with neither (melee sparks, the trap snap): all of it as the impact.
				if (flight <= 0 && impact <= 0)
					sequences.Append($"\timpact:\n\t\tLength: {frames.Count}\n\t\tScale: {scale}\n");

				sequences.Append('\n');
			}

			c.RepoYaml("sequences/weapons.yaml", sequences.ToString());

			// Spells and abilities (JW2_11 .maz, same record): image spell-<name> with all its frames as "effect".
			var spells = new StringBuilder(Header);
			foreach (var data in Records(c.Game.Archive("Jw2_11.trc")))
			{
				var (name, palette, frames, sounds) = ReadRecord(data);
				var image = "spell-" + Image(name)["weapon-".Length..];
				WriteSounds(c, image, sounds);
				if (frames.Count == 0)
					continue;

				c.WriteFile($"effects/{image}.png", Units.Sheet(frames, palette));
				spells.Append($"{image}:\n\teffect:\n\t\tFilename: effects/{image}.png\n\t\tLength: {frames.Count}\n\n");
			}

			c.RepoYaml("sequences/spells.yaml", spells.ToString());
		}

		static IEnumerable<byte[]> Records(TrcArchive archive) =>
			archive.Entries.Select(e => archive.Read(e.Index)).Where(d => d.Length >= Record);

		// The record (docs/formats/effect.md): name at 0x108; frame count at 0x200, then the palette and the frames;
		// sound count at 0x830, then the WAVs.
		static (string Name, Color[] Palette, List<(ChrFile.Frame Frame, bool Mirrored)> Frames, List<byte[]> Sounds) ReadRecord(byte[] data)
		{
			var name = Encoding.GetEncoding(949).GetString(data, 0x108, Math.Max(0, Array.IndexOf(data, (byte)0, 0x108, 0x40) - 0x108));
			var frameCount = BitConverter.ToInt32(data, 0x200);
			var at = Record;
			Color[] palette = null;
			var frames = new List<(ChrFile.Frame, bool)>();
			if (frameCount > 0)
			{
				palette = Units.ConvertPalette(data.AsSpan(at, 0x400).ToArray(), false);
				at += 0x400;
				for (var i = 0; i < frameCount; i++)
					frames.Add((ChrFile.ReadFrame(data, ref at), false));
			}

			var sounds = new List<byte[]>();
			var count = BitConverter.ToInt32(data, 0x830);
			for (var s = 0; s < count && at + 8 <= data.Length; s++)
			{
				var size = BitConverter.ToInt32(data, at + 4) + 8;
				sounds.Add(data.AsSpan(at, size).ToArray());
				at += size;
			}

			return (name, palette, frames, sounds);
		}

		static void WriteSounds(InstallContext c, string image, List<byte[]> sounds)
		{
			for (var s = 0; s < sounds.Count; s++)
				c.WriteFile($"sounds/{image}-{s}.wav", sounds[s]);
		}
	}
}
