using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using OpenRA.Primitives;

namespace OpenRA.Mods.Pw.AssetInstaller
{
	// Weapon effects (JW2_12 .wpn, docs/formats/effect.md): each weapon's art becomes image weapon-<name> in
	// effects/<image>.png with a "flight" sequence (the projectile: 8 facings x flight/8 frames when directional,
	// otherwise a tumbling loop) and an "impact" sequence; its sounds become sounds/<image>-<n>.wav. The weapons in
	// weapons/*.yaml reference them. The spells and abilities (JW2_11) become spell-<name>, in parts (SpellSequences).
	public static class Effects
	{
		const int Record = 0xadc;
		const string Header = "# Generated by install-assets (OpenRA.Mods.Pw/AssetInstaller/Effects.cs); do not edit.\n\n";

		// Impacts are drawn at half the original art's size.
		const string ImpactScale = "0.5";

		// The blending of glowing art (GlowingFlights, impacts not in SolidImpacts).
		const string Glow = "\t\tBlendMode: Screen\n";

		// Blit mode 8 (the record's 0x218 for the flight, 0x21c for the impact; only the Noise wave) draws none of the
		// art's colours: each pixel of the shape takes the screen pixel to its right (Pw.exe 0x48e261), a see-through
		// ripple of the ground. Sprites can't read the screen, so the art is drawn faint instead (Mod change).
		const int RippleMode = 8;
		const string Ripple = "\t\tAlpha: 0.2\n";

		// Effect art advances one frame per tick (all effects are updated once a game tick, 0x456aaa): weapons in flight
		// (0x4773bc) and at the impact (0x477563), spells in every part (0x478131, 0x478844, ...). 40 ms in sequence
		// ticks. The records have no frame delays (0x214-0x21c are blit modes).
		const int FrameTick = 40;

		// Smoke art: its palette holds only reds, which are the smoke's density, not colours (the Giant's bomb). It is
		// drawn as black of that opacity, so it darkens the ground beneath (dark green smoke on grass, as in the game).
		static readonly HashSet<string> Smoke = ["weapon-throw-bomb"];

		// Glowing art (fire, sparks, magic) is painted on black, which the game shows as light added to what lies beneath:
		// drawn with Screen blending, its black adds nothing (drawn opaque it showed black halos and outlines). Every
		// impact glows except these solid ones (debris, spikes, egg shell, bubble; the smoke darkens instead).
		static readonly HashSet<string> SolidImpacts =
		[
			"weapon-throw-bomb", "weapon-stone", "weapon-trap", "weapon-egg-throw", "weapon-bubble"
		];

		// Projectiles are solid (arrows, spears, stones) except these fireballs and magic shots.
		static readonly HashSet<string> GlowingFlights =
		[
			"weapon-shoot-sword-sprit", "weapon-phantom-fire", "weapon-wizard-firebolt", "weapon-redbolt", "weapon-whitebolt",
			"weapon-angelring", "weapon-kingdemon-fire", "weapon-noise-wave"
		];

		// Shots that leave their flight art behind them as a trail: every tick, an object at the shot's position that
		// plays the flight frames once, two ticks each (Pw.exe 0x477252, case 32 of the effect table at 0x47743c: the
		// KingDemon's fire, a line of flames that sweeps forward; the flames themselves do no damage). Their "trail"
		// sequence is that animation.
		static readonly HashSet<string> Trails = ["weapon-kingdemon-fire"];

		static Color[] SmokePalette(Color[] palette) =>
			palette.Select(c => c.A == 0 ? c : Color.FromArgb(c.R * c.A / 255, 0, 0, 0)).ToArray();

		public static string Image(string name) => "weapon-" + Regex.Replace(name.ToLowerInvariant(), "[^a-z0-9]+", "-").Trim('-');

		public static void Export(InstallContext c)
		{
			var sequences = new StringBuilder(Header);
			foreach (var data in Records(c.Game.Archive("Jw2_12.trc")))
			{
				var (name, palette, frames, sounds) = ReadRecord(data);
				var image = Image(name);
				var flightStart = BitConverter.ToInt32(data, 0x204);
				var flight = BitConverter.ToInt32(data, 0x208);
				var impact = BitConverter.ToInt32(data, 0x20c);
				var directional = BitConverter.ToInt32(data, 0x1fc) == 1;
				WriteSounds(c, image, sounds);
				if (frames.Count == 0)
					continue;

				c.WriteFile($"effects/{image}.png", Units.Sheet(frames, Smoke.Contains(image) ? SmokePalette(palette) : palette));
				sequences.Append(CultureInfo.InvariantCulture, $"{image}:\n\tDefaults:\n\t\tFilename: effects/{image}.png\n");
				if (flight > 0)
				{
					if (directional && flight % 8 == 0)
					{
						// The art's eight blocks run clockwise, from north (block k points at facing k: the Skeleton's arrow
						// and most others) or from one step clockwise of it (block k at facing k + 1: the Soldier's and the
						// Rhamphos's arrows). Art whose block 0 is much taller than wide and block 2 much wider than tall
						// starts at north.
						var n = flight / 8;
						var north = frames[flightStart].Frame;
						var east = frames[flightStart + 2 * n].Frame;
						var shift = north.Height * 2 >= north.Width * 3 && east.Width * 2 >= east.Height * 3 ? 0 : 7;
						var order = Enumerable.Range(0, 8).SelectMany(d => Enumerable.Range((d + shift) % 8 * n, n)).Select(f => f + flightStart);
						sequences.Append(CultureInfo.InvariantCulture, $"\tflight:\n\t\tFacings: -8\n\t\tLength: {n}\n\t\tFrames: {string.Join(", ", order)}\n" +
							$"\t\tTick: {FrameTick}\n");
					}
					else
						sequences.Append("\tflight:\n" + (flightStart > 0 ? $"\t\tStart: {flightStart}\n" : "") +
							$"\t\tLength: {flight}\n\t\tTick: {FrameTick}\n");

					if (BitConverter.ToInt32(data, 0x218) == RippleMode)
						sequences.Append(Ripple);
					else if (GlowingFlights.Contains(image))
						sequences.Append(Glow);

					if (Trails.Contains(image))
						sequences.Append("\ttrail:\n" + (flightStart > 0 ? $"\t\tStart: {flightStart}\n" : "") +
							$"\t\tLength: {flight}\n\t\tTick: 80\n" + (GlowingFlights.Contains(image) ? Glow : ""));
				}

				var impactScale = image == "weapon-bubble" ? "0.25" : ImpactScale;
				var impactBlend = BitConverter.ToInt32(data, 0x21c) == RippleMode ? Ripple : SolidImpacts.Contains(image) ? "" : Glow;
				var impactLook = $"\t\tScale: {impactScale}\n\t\tTick: {FrameTick}\n" + impactBlend;

				if (impact > 0)
					sequences.Append(CultureInfo.InvariantCulture, $"\timpact:\n\t\tStart: {flightStart + flight}\n\t\tLength: {impact}\n{impactLook}");

				// Art with neither (melee sparks, the trap snap): all of it as the impact.
				if (flight <= 0 && impact <= 0)
					sequences.Append(CultureInfo.InvariantCulture, $"\timpact:\n\t\tLength: {frames.Count}\n{impactLook}");

				sequences.Append('\n');
			}

			c.RepoYaml("sequences/weapons.yaml", sequences.ToString());

			// Spells and abilities (JW2_11 .maz, same record): image spell-<name> with all its frames as "effect".
			var spells = new StringBuilder(Header);
			foreach (var data in Records(c.Game.Archive("Jw2_11.trc")))
			{
				var (name, palette, frames, sounds) = ReadRecord(data);
				var image = "spell-" + Image(name)["weapon-".Length..];
				WriteSounds(c, image, sounds);
				if (frames.Count == 0)
					continue;

				c.WriteFile($"effects/{image}.png", Units.Sheet(frames, palette));
				spells.Append(SpellSequences(image, data, frames.Count));
			}

			c.RepoYaml("sequences/spells.yaml", spells.ToString());
		}

		// Spell art that is solid, not glowing light on black: the flying berries, the dropped stone, the gas cloud.
		static readonly HashSet<string> SolidSpellParts =
		[
			"spell-berry-fly/flight", "spell-drop-stone/effect", "spell-noxious-gas/effect"
		];

		// Caster frames drawn in 8 directions.
		static readonly HashSet<string> DirectionalCasts = ["spell-berry-fly", "spell-elf-build"];

		// A spell record's frames are, in order: the caster's (the Wizard's glow while it works its magic, the
		// ManaSpread's swirl), 0x208 flight frames, and 0x20c effect frames at the target, which are three variants of
		// 0x210 frames each when 0x22c is 1 (docs/formats/effect.md). Each part plays one frame per tick; the glowing
		// ones with Screen blending.
		static string SpellSequences(string image, byte[] data, int count)
		{
			var flight = Math.Max(0, BitConverter.ToInt32(data, 0x208));
			var impact = Math.Max(0, BitConverter.ToInt32(data, 0x20c));
			var cast = Math.Max(0, count - flight - impact);
			var variant = BitConverter.ToInt32(data, 0x22c) == 1 ? BitConverter.ToInt32(data, 0x210) : 0;
			var variants = variant > 0 && impact == 3 * variant ? 3 : 1;
			var part = variants == 3 ? variant : impact;

			var yaml = new StringBuilder($"{image}:\n\tDefaults:\n\t\tFilename: effects/{image}.png\n");
			void Part(string name, int start, int length, string solidKey)
			{
				if (length <= 0)
					return;

				yaml.Append(CultureInfo.InvariantCulture, $"\t{name}:\n\t\tStart: {start}\n\t\tLength: {length}\n\t\tTick: {FrameTick}\n");
				if (!SolidSpellParts.Contains($"{image}/{solidKey}"))
					yaml.Append(Glow);
			}

			// The Wizard's glow (Berry fly, Elf Build): 8 directions of cast / 8 frames, ordered as the weapons' flights.
			if (DirectionalCasts.Contains(image) && cast % 8 == 0)
			{
				var n = cast / 8;
				var order = Enumerable.Range(0, 8).SelectMany(d => Enumerable.Range((d + 7) % 8 * n, n));
				yaml.Append(CultureInfo.InvariantCulture, $"\tcast:\n\t\tFacings: -8\n\t\tLength: {n}\n\t\tFrames: {string.Join(", ", order)}\n" +
					$"\t\tTick: {FrameTick}\n{Glow}");
			}
			else
				Part("cast", 0, cast, "cast");
			Part("flight", cast, flight, "flight");
			for (var v = 0; v < variants; v++)
				Part(v == 0 ? "effect" : $"effect-{v + 1}", cast + flight + v * part, part, "effect");

			// Art that is all caster frames (Level up): its whole as the effect.
			if (impact == 0 && flight == 0)
				Part("effect", 0, cast, "effect");

			return yaml.Append('\n').ToString();
		}

		static IEnumerable<byte[]> Records(TrcArchive archive) =>
			archive.Entries.Select(e => archive.Read(e.Index)).Where(d => d.Length >= Record);

		// The record (docs/formats/effect.md): name at 0x108; frame count at 0x200, then the palette and the frames;
		// sound count at 0x830, then the WAVs.
		static (string Name, Color[] Palette, List<(ChrFile.Frame Frame, bool Mirrored)> Frames, List<byte[]> Sounds) ReadRecord(byte[] data)
		{
			var name = Encoding.GetEncoding(949).GetString(data, 0x108, Math.Max(0, Array.IndexOf(data, (byte)0, 0x108, 0x40) - 0x108));
			var frameCount = BitConverter.ToInt32(data, 0x200);
			var at = Record;
			Color[] palette = null;
			var frames = new List<(ChrFile.Frame, bool)>();
			if (frameCount > 0)
			{
				palette = Units.ConvertPalette(data.AsSpan(at, 0x400).ToArray(), false);
				at += 0x400;
				for (var i = 0; i < frameCount; i++)
					frames.Add((ChrFile.ReadFrame(data, ref at), false));
			}

			var sounds = new List<byte[]>();
			var count = BitConverter.ToInt32(data, 0x830);
			for (var s = 0; s < count && at + 8 <= data.Length; s++)
			{
				var size = BitConverter.ToInt32(data, at + 4) + 8;
				sounds.Add(data.AsSpan(at, size).ToArray());
				at += size;
			}

			return (name, palette, frames, sounds);
		}

		static void WriteSounds(InstallContext c, string image, List<byte[]> sounds)
		{
			for (var s = 0; s < sounds.Count; s++)
				c.WriteFile($"sounds/{image}-{s}.wav", sounds[s]);
		}
	}
}
