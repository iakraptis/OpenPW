using System;
using System.Collections.Generic;
using System.Text;
using OpenRA.FileFormats;
using OpenRA.Graphics;

namespace OpenRA.Mods.Pw.AssetInstaller
{
	// Interface art (docs/formats/ui.md). So far the mouse cursors: JW2_01 Mouse100.mcs holds 100 cursors of 32x32
	// RGB565 pixels (black transparent), each after a 16-byte header with its hotspot. They become cursors/cursors.png
	// and the generated mods/pw/cursors/default.yaml. Which original cursor serves which OpenRA cursor is chosen here
	// (Mousec.dat, the original's own table, is not decoded).
	public static class Chrome
	{
		const int CursorSize = 32;
		const int CursorCount = 100;
		const int IconSize = 38;
		const int LargeIconSize = 50;
		static readonly string[] Races = { "primitive", "elf", "tyrano", "demon" };

		// OpenRA cursor name, first original cursor, frame count. The "blocked" cursors keep the normal pointer: the red
		// no-entry signs (20-32) are not used.
		static readonly (string Name, int Start, int Length)[] Cursors =
		{
			("default", 0, 1),
			("generic-blocked", 0, 1),
			("select", 64, 8),
			("joystick-all", 0, 1),

			// Moving keeps the normal pointer: the original does not change the cursor over open ground.
			("move", 0, 1),
			("move-blocked", 0, 1),
			("attack", 40, 8),
			("attackoutsiderange", 40, 8),
			("attackmove", 48, 8),
			("attackmove-blocked", 0, 1),
			("assaultmove", 48, 8),
			("assaultmove-blocked", 0, 1),

			// The ring with the arrow pointing down: loading units into a transport.
			("enter", 92, 8),
			("enter-blocked", 0, 1),
			("capture", 80, 4),
			("capture-blocked", 0, 1),
			("harvest", 36, 1),
			("deploy", 72, 1),
			("deploy-blocked", 0, 1),
			("ability", 56, 8),
			("heal", 56, 8),
			("repair", 72, 1),
			("repair-blocked", 0, 1),
			("goldwrench", 72, 1),
			("goldwrench-blocked", 0, 1),
			("sell", 7, 1),
			("sell-blocked", 0, 1),
			("c4", 40, 1),
			("wait", 13, 1),
		};

		// Scroll arrows by direction; scrolling against the map edge shows the same arrow.
		static readonly (string Direction, int Cursor)[] Scroll =
		{
			("t", 1), ("tr", 3), ("r", 2), ("br", 6), ("b", 4), ("bl", 12), ("l", 8), ("tl", 9)
		};

		public static void Export(InstallContext c)
		{
			var mcs = c.Game.Archive("Jw2_01.trc").Read("Mouse100.mcs");
			if (BitConverter.ToInt32(mcs, 4) != CursorCount)
				throw new InvalidOperationException("Mouse100.mcs: unexpected cursor count");

			var rgba = new byte[4 * CursorSize * CursorSize * CursorCount];
			var hotspots = new (int X, int Y)[CursorCount];
			for (var i = 0; i < CursorCount; i++)
			{
				var at = 16 + i * (16 + 2 * CursorSize * CursorSize);
				hotspots[i] = (BitConverter.ToInt32(mcs, at), BitConverter.ToInt32(mcs, at + 4));
				for (var p = 0; p < CursorSize * CursorSize; p++)
				{
					var c565 = BitConverter.ToUInt16(mcs, at + 16 + 2 * p);
					if (c565 == 0)
						continue;

					var y = p / CursorSize;
					var x = p % CursorSize;
					var o = 4 * (y * CursorSize * CursorCount + i * CursorSize + x);
					rgba[o] = (byte)((c565 >> 11) * 255 / 31);
					rgba[o + 1] = (byte)(((c565 >> 5) & 63) * 255 / 63);
					rgba[o + 2] = (byte)((c565 & 31) * 255 / 31);
					rgba[o + 3] = 255;
				}
			}

			var meta = new Dictionary<string, string> { ["FrameSize"] = $"{CursorSize},{CursorSize}", ["FrameAmount"] = $"{CursorCount}" };
			c.WriteFile("cursors/cursors.png", new Png(rgba, SpriteFrameType.Rgba32, CursorSize * CursorCount, CursorSize, null, meta).Save());

			var yaml = new StringBuilder("# Generated by install-assets (OpenRA.Mods.Pw/AssetInstaller/Chrome.cs) from Mouse100.mcs; edit the table there.\n");
			yaml.Append("Cursors:\n\tcursors/cursors.png:\n");
			void Add(string name, int start, int length)
			{
				yaml.Append($"\t\t{name}:\n\t\t\tStart: {start}\n");
				if (length > 1)
					yaml.Append($"\t\t\tLength: {length}\n");

				// OpenRA measures the hotspot from the centre of the frame, the original from its top-left corner.
				yaml.Append($"\t\t\tX: {hotspots[start].X - CursorSize / 2}\n\t\t\tY: {hotspots[start].Y - CursorSize / 2}\n");
			}

			foreach (var (name, start, length) in Cursors)
				Add(name, start, length);

			foreach (var (direction, cursor) in Scroll)
			{
				Add($"scroll-{direction}", cursor, 1);
				Add($"scroll-{direction}-blocked", cursor, 1);
				Add($"joystick-{direction}-blocked", cursor, 1);
			}

			c.RepoYaml("cursors/default.yaml", yaml.ToString());
			ExportPortraits(c);
		}

		// Small portraits, 38x38, one per unit type (JW2_02 Char_small.t, 170 frames), used as build icons: each unit and
		// building image has an "icon" sequence pointing at its frame (Units.cs). The archive holds the portraits once
		// per race, each in its own frame style: blocks of 13 entries for Primitive, Elf, Tyrano, Demon, with the
		// palette first and the sheet second. Each type takes its own race's version (wild creatures the Primitive one).
		// The upgrade buttons (Upgrade.trt, 48) and item buttons (Item.trt, 32) are written once per race, in that race's
		// style: chrome/upgrades-<race>.png and chrome/items-<race>.png, and the ability buttons (Magic.trt, 16) as
		// chrome/magic-<race>.png (docs/formats/ui.md).
		static void ExportPortraits(InstallContext c)
		{
			var archive = c.Game.Archive("Jw2_02.trc");
			var raceBlock = new Dictionary<string, int> { ["primitive"] = 0, ["elf"] = 1, ["tyrano"] = 2, ["demon"] = 3, ["wild"] = 0 };
			c.WriteFile("chrome/portraits.png", IconSheet(archive, 170, type => 13 * raceBlock[Units.Race(type)], 0));

			// The larger portraits of the selection panel (Char_middle, 50x50, Char_small's palette).
			c.WriteFile("chrome/portraits-large.png", IconSheet(archive, 170, type => 13 * raceBlock[Units.Race(type)], 0, 2, LargeIconSize));
			for (var race = 0; race < Races.Length; race++)
			{
				var block = 13 * race;
				c.WriteFile($"chrome/upgrades-{Races[race]}.png", IconSheet(archive, 48, _ => block, 9));
				c.WriteFile($"chrome/items-{Races[race]}.png", IconSheet(archive, 32, _ => block, 11));
				c.WriteFile($"chrome/magic-{Races[race]}.png", IconSheet(archive, 16, _ => block, 5));
			}

			ExportInterfaceBars(c, archive);
			ExportResourceIcons(c, archive);
		}

		// The in-game interface of each race (docs/formats/ui.md): the bottom bar Intfbg.spr (800 wide, its green
		// surround made transparent) as chrome/bar-<race>.png, and the bar's buttons (Menu, Allies, Msg, each released
		// and pressed: .spz frames) side by side in chrome/bar-<race>-buttons.png. JW2_02 holds them in blocks of 8
		// from entry 306: palette, bar, then the six buttons.
		static void ExportInterfaceBars(InstallContext c, TrcArchive archive)
		{
			for (var race = 0; race < Races.Length; race++)
			{
				var block = 306 + 8 * race;
				var palette = archive.Read(block);
				var bar = archive.Read(block + 1);
				var width = BitConverter.ToUInt16(bar, 0);
				var height = BitConverter.ToUInt16(bar, 2);

				// Chrome images need power-of-two sizes: the bar sits at the top left of a padded sheet.
				var sheetWidth = PowerOfTwo(width);
				var sheetHeight = PowerOfTwo(height);
				var rgba = new byte[4 * sheetWidth * sheetHeight];
				for (var y = 0; y < height; y++)
				{
					for (var x = 0; x < width; x++)
					{
						var index = bar[12 + y * width + x];
						var (r, g, b) = (palette[4 * index], palette[4 * index + 1], palette[4 * index + 2]);
						var transparent = r < 16 && g > 240 && b < 16;
						var o = 4 * (y * sheetWidth + x);
						rgba[o] = r;
						rgba[o + 1] = g;
						rgba[o + 2] = b;
						rgba[o + 3] = transparent ? (byte)0 : (byte)255;
					}
				}

				c.WriteFile($"chrome/bar-{Races[race]}.png", new Png(rgba, SpriteFrameType.Rgba32, sheetWidth, sheetHeight).Save());

				var colors = Units.ConvertPalette(palette, false);
				var buttons = new List<(ChrFile.Frame Frame, bool Mirrored)>();
				for (var i = 0; i < 6; i++)
				{
					var at = 0;
					buttons.Add((ChrFile.ReadFrame(archive.Read(block + 2 + i), ref at), false));
				}

				c.WriteFile($"chrome/bar-{Races[race]}-buttons.png", Units.Sheet(buttons, colors));
			}
		}

		// The resource icons (JW2_02 Food, Water, Stone, House: 14x14 .spz, palette Misc.pnt at entry 256) side by side
		// in chrome/resources.png, 16 px apart on a power-of-two sheet.
		static void ExportResourceIcons(InstallContext c, TrcArchive archive)
		{
			const int Cell = 16;
			var palette = Units.ConvertPalette(archive.Read(256), false);
			var rgba = new byte[4 * 64 * Cell];
			for (var i = 0; i < 4; i++)
			{
				var at = 0;
				var frame = ChrFile.ReadFrame(archive.Read(289 + i), ref at);
				for (var y = 0; y < frame.Height; y++)
				{
					for (var x = 0; x < frame.Width; x++)
					{
						var color = palette[frame.Pixels[y * frame.Width + x]];
						var o = 4 * (y * 64 + i * Cell + x);
						rgba[o] = color.R;
						rgba[o + 1] = color.G;
						rgba[o + 2] = color.B;
						rgba[o + 3] = color.A;
					}
				}
			}

			c.WriteFile("chrome/resources.png", new Png(rgba, SpriteFrameType.Rgba32, 64, Cell).Save());
		}

		static int PowerOfTwo(int n)
		{
			var p = 1;
			while (p < n)
				p *= 2;

			return p;
		}

		// A row of count square icons: icon i from the sheet at blockOf(i) + sheetEntry (by default right after the
		// palette at blockOf(i) + paletteEntry), size x size each (38 by default).
		static byte[] IconSheet(TrcArchive archive, int count, Func<int, int> blockOf, int paletteEntry, int sheetEntry = -1, int size = IconSize)
		{
			var rgba = new byte[4 * size * size * count];
			for (var icon = 0; icon < count; icon++)
			{
				var palette = archive.Read(blockOf(icon) + paletteEntry);
				var sheet = archive.Read(blockOf(icon) + (sheetEntry < 0 ? paletteEntry + 1 : sheetEntry));
				for (var p = 0; p < size * size; p++)
				{
					var index = sheet[icon * size * size + p];
					var o = 4 * (p / size * size * count + icon * size + p % size);
					rgba[o] = palette[4 * index];
					rgba[o + 1] = palette[4 * index + 1];
					rgba[o + 2] = palette[4 * index + 2];
					rgba[o + 3] = 255;
				}
			}

			var meta = new Dictionary<string, string> { ["FrameSize"] = $"{size},{size}", ["FrameAmount"] = $"{count}" };
			return new Png(rgba, SpriteFrameType.Rgba32, size * count, size, null, meta).Save();
		}
	}
}
