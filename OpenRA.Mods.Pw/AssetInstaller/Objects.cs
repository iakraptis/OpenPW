using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace OpenRA.Mods.Pw.AssetInstaller
{
	// Map objects (docs/formats/doo.md, map.md): the doodads of each tileset and the berry bushes, as sprite sheets
	// (objects/<image>.png), their sequences (generated mods/pw/sequences/objects.yaml) and one map actor per doodad
	// variant and per bush variant (generated mods/pw/rules/objects.yaml; the templates are in rules/defaults.yaml).
	// Maps.cs places them by the same names.
	public static class Objects
	{
		// JW2_03 entry tileset * 15 + 1 + n: J00-J11 (D, R) and the cave; the altar (14) is never placed.
		public const int Doodads = 13;

		// The original draws an object from its cell's top-left corner; OpenRA from the actor's centre.
		const string DoodadOffset = "-16, -16";
		const string BushOffset = "-32, -16";
		const int ItemCount = 32;

		public static string DoodadActor(string tileset, int doodad, int variant) { return $"doodad-{tileset}-{doodad:D2}-{variant}"; }

		public static string BushActor(int variant) { return $"berry-bush-{variant}"; }

		public static string ItemImage(int item) { return $"item-{item:D2}"; }

		public static void Export(InstallContext c)
		{
			var sequences = new StringBuilder("# Generated by install-assets (OpenRA.Mods.Pw/AssetInstaller/Objects.cs); do not edit.\n\n");
			var rules = new StringBuilder("# Generated by install-assets (OpenRA.Mods.Pw/AssetInstaller/Objects.cs); do not edit.\n");
			rules.Append("# One actor per doodad variant and per berry bush variant, placed by the converted maps.\n\n");

			var archive = c.Game.Archive("Jw2_03.trc");
			for (var t = 0; t < Terrain.Tilesets.Length; t++)
			{
				var tileset = Terrain.Tilesets[t].Name;
				for (var n = 0; n < Doodads; n++)
				{
					var data = archive.Read(t * 15 + 1 + n);
					var (palette, variants) = ReadDoo(data);
					var image = $"doodad-{tileset}-{n:D2}";
					var frames = new List<(ChrFile.Frame, bool)>();
					foreach (var v in variants)
						frames.Add((v, false));

					c.WriteFile($"objects/{image}.png", Units.Sheet(frames, Units.ConvertPalette(palette, false)));
					sequences.Append(CultureInfo.InvariantCulture, $"{image}:\n\tDefaults:\n\t\tFilename: objects/{image}.png\n\t\tOffset: {DoodadOffset}\n");
					for (var v = 0; v < variants.Count; v++)
					{
						sequences.Append(CultureInfo.InvariantCulture, $"\tv{v}:\n\t\tStart: {v}\n");
						rules.Append(CultureInfo.InvariantCulture, $"{DoodadActor(tileset, n, v)}:\n\tInherits: ^Doodad\n\tRenderSprites:\n\t\tImage: {image}\n");
						rules.Append(CultureInfo.InvariantCulture, $"\tWithSpriteBody:\n\t\tSequence: v{v}\n\tMapEditorData:\n\t\tRequireTilesets: {Terrain.Tilesets[t].Id}\n\n");
					}

					sequences.Append('\n');
				}
			}

			// Berry bushes: JW2_07 Bery<v><s>.spz (one frame each, stage s = how much is left) with palette Bery<v>.pnt.
			var effects = c.Game.Archive("Jw2_07.trc");
			for (var v = 0; v < 4; v++)
			{
				var palette = effects.Read($"Bery{v}.pnt");
				var frames = new List<(ChrFile.Frame, bool)>();
				for (var s = 0; s < 4; s++)
				{
					var at = 0;
					frames.Add((ChrFile.ReadFrame(effects.Read($"Bery{v}{s}.spz"), ref at), false));
				}

				var image = BushActor(v);
				c.WriteFile($"objects/{image}.png", Units.Sheet(frames, Units.ConvertPalette(palette, false)));
				sequences.Append(CultureInfo.InvariantCulture, $"{image}:\n\tDefaults:\n\t\tFilename: objects/{image}.png\n\t\tOffset: {BushOffset}\n");
				sequences.Append("\tidle:\n\t\tStart: 0\n\t\tLength: 4\n\n");
				rules.Append(CultureInfo.InvariantCulture, $"{image}:\n\tInherits: ^BerryBush\n\tRenderSprites:\n\t\tImage: {image}\n\n");
			}

			// Items on the ground (Blacksmith items before a unit picks them up): JW2_07 I<nn>.spz, one per Item.itm record,
			// with palette Item.pnt. Image item-<nn>, whose icon is its button (Item.trt has one per record; the chrome stage
			// writes the sheets). The item actors are in rules/<race>/items.yaml.
			var itemPalette = Units.ConvertPalette(effects.Read("Item.pnt"), false);
			var items = new List<(ChrFile.Frame, bool)>();
			for (var i = 0; i < ItemCount; i++)
			{
				var at = 0;
				items.Add((ChrFile.ReadFrame(effects.Read($"I{i:D2}.spz"), ref at), false));
			}

			c.WriteFile("objects/items.png", Units.Sheet(items, itemPalette));
			for (var i = 0; i < ItemCount; i++)
				sequences.Append(CultureInfo.InvariantCulture, $"{ItemImage(i)}:\n\tidle:\n\t\tFilename: objects/items.png\n\t\tStart: {i}\n" +
					$"\ticon:\n\t\tFilename: chrome/items-primitive.png\n\t\tStart: {i}\n\n");

			c.RepoYaml("sequences/objects.yaml", sequences.ToString());
			c.RepoYaml("rules/objects.yaml", rules.ToString());
		}

		// 0x39c-byte record, palette, then 4 blocks of [u32 count][u32 size][frames] (docs/formats/doo.md).
		static (byte[] Palette, List<ChrFile.Frame> Variants) ReadDoo(byte[] data)
		{
			const int Record = 0x39c;
			var palette = data.AsSpan(Record, 0x400).ToArray();
			var variants = new List<ChrFile.Frame>();
			var at = Record + 0x400;
			for (var v = 0; v < 4; v++)
			{
				var count = BitConverter.ToInt32(data, at);
				var next = at + 8 + BitConverter.ToInt32(data, at + 4);
				at += 8;
				if (count > 0)
					variants.Add(ChrFile.ReadFrame(data, ref at));

				at = next;
			}

			return (palette, variants);
		}
	}
}
