using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using OpenRA.FileFormats;
using OpenRA.Graphics;
using OpenRA.Primitives;

namespace OpenRA.Mods.Pw.AssetInstaller
{
	// Every unit and building type of JW2_09.TRC (docs/formats/chr.md) as an RGBA sprite sheet, units/<image>.png, with
	// per-frame offsets; and their sequences, generated into mods/pw/sequences/<race>.yaml (kept in git).
	// - Colours: the player colour ramp (palette 245-254) moves into PlayerColorShift's hue band (rules/palettes.yaml),
	//   other pixels in that band are nudged out of it; index 1 (shadow) becomes half-transparent black.
	// - Directions: a group stores N, NE, E, SE, S; SW, W and NW are written as mirrored copies of SE, E, NE.
	// - Timing: each sequence lists the original frame per animation step (one game tick each, Tick 40 = one world tick).
	public static class Units
	{
		const int SheetWidth = 2048;
		const float ColorShiftHue = 0.835f;
		const float ColorShiftMin = 0.825f;
		const float ColorShiftMax = 0.845f;

		// Facings clockwise from north: the direction block (1-5) and whether it is mirrored.
		static readonly (int Block, bool Mirrored)[] Facings =
		{
			(1, false), (2, false), (3, false), (4, false), (5, false), (4, true), (3, true), (2, true)
		};

		static readonly int[] Workers = { 0, 16, 32, 48 };
		static readonly string[] WorkerGroups = { null, null, null, null, "gather", "walk-carry-a", "walk-carry-b", "stand-carry-a", "stand-carry-b", "build" };

		public static string Race(int type)
		{
			if (type < 96)
				return type < 16 ? "primitive" : type < 32 ? "elf" : type < 48 ? "tyrano" : type < 64 ? "demon" : "wild";

			return type < 112 ? "primitive" : type < 128 ? "elf" : type < 144 ? "tyrano" : type < 160 ? "demon" : "wild";
		}

		public static string ImageName(int type, ChrFile chr)
		{
			var slug = Regex.Replace(chr.Name.ToLowerInvariant(), "[^a-z0-9]+", "-").Trim('-');
			return $"{Race(type)}-{slug}";
		}

		public static void Export(InstallContext c)
		{
			var archive = c.Game.Archive("Jw2_09.trc");
			var sequences = new SortedDictionary<string, StringBuilder>(StringComparer.Ordinal);
			var voices = new StringBuilder("# Generated by install-assets (OpenRA.Mods.Pw/AssetInstaller/Units.cs) from JW2_09.TRC; do not edit.\n" +
				"# One voice set per unit image (docs/formats/chr.md, Sounds); the files are sounds/<image>-<voice>-<n>.wav.\n\n");
			foreach (var entry in archive.Entries)
			{
				var data = archive.Read(entry.Index);
				if (data.Length < ChrFile.RecordSize + 0x400)
					continue;

				var chr = new ChrFile(data);
				if (chr.Frames.All(g => g.Count == 0))
					continue;

				var image = ImageName(entry.Index, chr);
				var race = Race(entry.Index);
				if (!sequences.TryGetValue(race, out var yaml))
					sequences[race] = yaml = new StringBuilder();

				yaml.Append(Export(c, entry.Index, chr, image));
				voices.Append(ExportSounds(c, chr, image));
			}

			c.RepoYaml("voices/units.yaml", voices.ToString());

			foreach (var (race, yaml) in sequences)
				c.RepoYaml($"sequences/{race}.yaml",
					$"# Generated by install-assets (OpenRA.Mods.Pw/AssetInstaller/Units.cs) from JW2_09.TRC; do not edit.\n\n{yaml}");
		}

		// The .chr sound groups the game plays, by OpenRA voice: 0 select, 1 acknowledge, 2 attack (on attack frames),
		// 4 die, 5 work (gathering, building), 8 construction finished. Groups 3, 6 and 7 are never played.
		static readonly (int Group, string Voice)[] VoiceGroups =
		{
			(0, "Select"), (1, "Action"), (2, "Attack"), (4, "Die"), (5, "Work"), (8, "Built"),
		};

		static string ExportSounds(InstallContext c, ChrFile chr, string image)
		{
			var yaml = new StringBuilder();
			foreach (var (group, voice) in VoiceGroups)
			{
				var files = new List<string>();
				for (var n = 0; n < chr.Sounds[group].Count; n++)
				{
					var file = $"{image}-{voice.ToLowerInvariant()}-{n}.wav";
					c.WriteFile($"sounds/{file}", chr.Sounds[group][n]);
					files.Add(file);
				}

				if (files.Count > 0)
					yaml.Append($"\t\t{voice}: {string.Join(", ", files)}\n");
			}

			return yaml.Length == 0 ? "" : $"{image}:\n\tVoices:\n{yaml}\n";
		}

		static string Export(InstallContext c, int type, ChrFile chr, string image)
		{
			var palette = ConvertPalette(chr.Palette);
			var frames = new List<(ChrFile.Frame Frame, bool Mirrored)>();
			var groupStart = new int[ChrFile.Groups];
			var mirrorStart = new Dictionary<(int Group, int Block), int>();

			for (var g = 0; g < ChrFile.Groups; g++)
			{
				groupStart[g] = frames.Count;
				frames.AddRange(chr.Frames[g].Select(f => (f, false)));
			}

			for (var g = 0; g < ChrFile.Groups; g++)
			{
				if (!Directional(chr, g))
					continue;

				for (var b = 2; b <= 4; b++)
				{
					mirrorStart[(g, b)] = frames.Count;
					var (start, end) = Block(chr, g, b);
					for (var i = start; i < end; i++)
						frames.Add((chr.Frames[g][i], true));
				}
			}

			c.WriteFile($"units/{image}.png", Sheet(frames, palette));

			var building = type >= 96;
			var yaml = new StringBuilder($"{image}:\n\tDefaults:\n\t\tFilename: units/{image}.png\n\t\tTick: 40\n");

			// The original anchors a building at its footprint's top-left corner (.chr 0x330/0x334, in 32 px cells);
			// OpenRA draws it around the footprint's centre.
			if (building && chr.Int(0x330) > 0 && chr.Int(0x334) > 0)
			{
				var x = -16 * chr.Int(0x330);
				var y = -16 * chr.Int(0x334);
				yaml.Append($"\t\tOffset: {x}, {y}\n");
			}

			for (var g = 0; g < ChrFile.Groups; g++)
			{
				var count = chr.Frames[g].Count;
				if (count == 0)
					continue;

				var steps = chr.Sequence(g);
				if (building && g == 0)
				{
					// Construction stages, then the finished building.
					if (count > 1)
						yaml.Append($"\tmake:\n\t\tStart: {groupStart[g]}\n\t\tLength: {count - 1}\n");

					yaml.Append($"\tidle:\n\t\tStart: {groupStart[g] + count - 1}\n");
					continue;
				}

				var name = GroupName(type, building, g);
				if (!Directional(chr, g))
				{
					var list = steps.Length > 0 ? steps.Select(s => groupStart[g] + Math.Min(s, count - 1)) : Enumerable.Range(groupStart[g], count);
					yaml.Append($"\t{name}:\n\t\tFrames: {string.Join(", ", list)}\n\t\tLength: {list.Count()}\n");
					continue;
				}

				var all = new List<int>();
				foreach (var (block, mirrored) in Facings)
				{
					var (start, end) = Block(chr, g, block);
					var first = mirrored ? mirrorStart[(g, block)] : groupStart[g] + start;
					var length = end - start;
					var blockSteps = steps.Length > 0 ? steps : Enumerable.Range(0, length).ToArray();
					all.AddRange(blockSteps.Select(s => first + Math.Clamp(s, 0, Math.Max(0, length - 1))));
				}

				yaml.Append($"\t{name}:\n\t\tFacings: -8\n\t\tLength: {all.Count / 8}\n\t\tFrames: {string.Join(", ", all)}\n");
			}

			// The build icon: the type's portrait (Chrome.cs writes the sheet, one frame per type). Its own zero offset,
			// as the image's Defaults carry the building footprint offset.
			yaml.Append($"\ticon:\n\t\tFilename: chrome/portraits.png\n\t\tStart: {type}\n\t\tOffset: 0, 0\n");
			return yaml.Append('\n').ToString();
		}

		static string GroupName(int type, bool building, int g)
		{
			if (building)
				return g == 2 ? "attack" : g == 11 ? "active" : $"group{g}";

			switch (g)
			{
				case 0: return "stand";
				case 1: return "walk";
				case 2: return "attack";
				case 3: return "die";
			}

			if (Workers.Contains(type) && g < WorkerGroups.Length)
				return WorkerGroups[g];

			return $"group{g}";
		}

		// Five direction blocks with increasing start frames; otherwise (flyer deaths, building groups) one block.
		static bool Directional(ChrFile chr, int g)
		{
			var count = chr.Frames[g].Count;
			if (count < 5)
				return false;

			for (var b = 1; b < 5; b++)
				if (chr.BlockStart(g, b + 1) <= chr.BlockStart(g, b))
					return false;

			return chr.BlockStart(g, 5) < count;
		}

		static (int Start, int End) Block(ChrFile chr, int g, int b)
		{
			var start = chr.BlockStart(g, b);
			var end = b < 5 ? chr.BlockStart(g, b + 1) : chr.Frames[g].Count;
			return (start, end);
		}

		// RGBA per palette index (256 x RGB0). With playerColor, the ramp 245-254 becomes the player colour band; without
		// it (map objects), the band is only kept clear.
		public static Color[] ConvertPalette(byte[] source, bool playerColor = true)
		{
			var colors = new Color[256];
			for (var i = 0; i < 256; i++)
			{
				var color = Color.FromArgb(source[4 * i], source[4 * i + 1], source[4 * i + 2]);
				var (hue, saturation, value) = Color.RgbToHsv(color.R / 255f, color.G / 255f, color.B / 255f);
				if (playerColor && i >= 245 && i <= 254)
					color = Color.FromAhsv(ColorShiftHue, 1f, value);
				else if (hue >= ColorShiftMin && hue <= ColorShiftMax && saturation > 0)
					color = Color.FromAhsv(hue < ColorShiftHue ? ColorShiftMin - 0.005f : ColorShiftMax + 0.005f, saturation, value);

				colors[i] = color;
			}

			colors[0] = Color.Transparent;
			colors[1] = Color.FromArgb(128, 0, 0, 0);
			return colors;
		}

		// Shelf-packed frames with a one pixel gap; Frame[i] = region;offset from the sprite centre.
		public static byte[] Sheet(List<(ChrFile.Frame Frame, bool Mirrored)> frames, Color[] palette)
		{
			var regions = new List<Rectangle>();
			int x = 0, y = 0, rowHeight = 0;
			foreach (var (f, _) in frames)
			{
				var w = Math.Max(1, f.Width);
				var h = Math.Max(1, f.Height);
				if (x + w > SheetWidth)
				{
					x = 0;
					y += rowHeight + 1;
					rowHeight = 0;
				}

				regions.Add(new Rectangle(x, y, w, h));
				x += w + 1;
				rowHeight = Math.Max(rowHeight, h);
			}

			var height = Math.Max(1, y + rowHeight);
			var rgba = new byte[4 * SheetWidth * height];
			var meta = new Dictionary<string, string>();
			for (var i = 0; i < frames.Count; i++)
			{
				var (f, mirrored) = frames[i];
				var r = regions[i];
				for (var py = 0; py < f.Height; py++)
				{
					for (var px = 0; px < f.Width; px++)
					{
						var c = palette[f.Pixels[py * f.Width + (mirrored ? f.Width - 1 - px : px)]];
						var at = 4 * ((r.Y + py) * SheetWidth + r.X + px);
						rgba[at] = c.R;
						rgba[at + 1] = c.G;
						rgba[at + 2] = c.B;
						rgba[at + 3] = c.A;
					}
				}

				var left = mirrored ? f.MirroredOffsetX : f.OffsetX;
				var centreX = left + f.Width / 2f;
				var centreY = f.OffsetY + f.Height / 2f;
				meta[$"Frame[{i}]"] = FormattableString.Invariant($"{r.X},{r.Y},{r.Width},{r.Height};{centreX},{centreY}");
			}

			return new Png(rgba, SpriteFrameType.Rgba32, SheetWidth, height, null, meta).Save();
		}
	}
}
